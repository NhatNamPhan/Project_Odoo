DROP TABLE IF EXISTS NGUOINHANTHONGBAO CASCADE;
DROP TABLE IF EXISTS TEPTHONGBAO CASCADE;
DROP TABLE IF EXISTS THONGBAO CASCADE;
DROP TABLE IF EXISTS TINNHAN CASCADE;
DROP TABLE IF EXISTS PHIEUCHAMDIEM CASCADE;
DROP TABLE IF EXISTS HOIDONGGIANGVIEN CASCADE;
DROP TABLE IF EXISTS HINHANHDETAI CASCADE;
DROP TABLE IF EXISTS BAOCAO CASCADE;
DROP TABLE IF EXISTS DETAI CASCADE;
DROP TABLE IF EXISTS HOIDONG CASCADE;
DROP TABLE IF EXISTS NGANHANGDETAI CASCADE;
DROP TABLE IF EXISTS DANGKY CASCADE;
DROP TABLE IF EXISTS DOTBAOCAO CASCADE;
DROP TABLE IF EXISTS DOTDOAN CASCADE;
DROP TABLE IF EXISTS GIANGVIEN CASCADE;
DROP TABLE IF EXISTS SINHVIEN CASCADE;
DROP TABLE IF EXISTS LOPSINHHOAT CASCADE;
DROP TABLE IF EXISTS CHUYENNGANH CASCADE;
DROP TABLE IF EXISTS NGUOIDUNG CASCADE;
DROP TABLE IF EXISTS VAITRO CASCADE;

-- 1. BẢNG VAITRO
CREATE TABLE VAITRO (
    idVaiTro VARCHAR(50) PRIMARY KEY,
    tenVaiTro VARCHAR(255) NOT NULL
);

-- 2. BẢNG NGUOIDUNG
CREATE TABLE NGUOIDUNG (
    idNguoiDung VARCHAR(50) PRIMARY KEY,
    idVaiTro VARCHAR(50) NOT NULL,
    hoTen VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    matKhau VARCHAR(255) NOT NULL,
    sdt VARCHAR(20),
    trangThai VARCHAR(50) DEFAULT 'DANG_HOAT_DONG',
    ngayTao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NGUOIDUNG_VAITRO FOREIGN KEY (idVaiTro) REFERENCES VAITRO(idVaiTro)
);

-- 3. BẢNG CHUYENNGANH
CREATE TABLE CHUYENNGANH (
    idChuyenNganh VARCHAR(50) PRIMARY KEY,
    maChuyenNganh VARCHAR(50) NOT NULL UNIQUE,
    tenChuyenNganh VARCHAR(255) NOT NULL
);

-- 4. BẢNG LOPSINHHOAT
CREATE TABLE LOPSINHHOAT (
    idLopSinhHoat VARCHAR(50) PRIMARY KEY,
    idChuyenNganh VARCHAR(50) NOT NULL,
    maLop VARCHAR(50) NOT NULL UNIQUE,
    tenLop VARCHAR(255) NOT NULL,
    nienKhoa VARCHAR(50) NOT NULL,
    CONSTRAINT FK_LOPSINHHOAT_CHUYENNGANH FOREIGN KEY (idChuyenNganh) REFERENCES CHUYENNGANH(idChuyenNganh)
);

-- 5. BẢNG SINHVIEN
CREATE TABLE SINHVIEN (
    idSinhVien VARCHAR(50) PRIMARY KEY,
    idNguoiDung VARCHAR(50) NOT NULL UNIQUE,
    idLopSinhHoat VARCHAR(50) NOT NULL,
    maSV VARCHAR(50) NOT NULL UNIQUE,
    CONSTRAINT FK_SINHVIEN_NGUOIDUNG FOREIGN KEY (idNguoiDung) REFERENCES NGUOIDUNG(idNguoiDung),
    CONSTRAINT FK_SINHVIEN_LOPSINHHOAT FOREIGN KEY (idLopSinhHoat) REFERENCES LOPSINHHOAT(idLopSinhHoat)
);

-- 6. BẢNG GIANGVIEN
CREATE TABLE GIANGVIEN (
    idGiangVien VARCHAR(50) PRIMARY KEY,
    idNguoiDung VARCHAR(50) NOT NULL UNIQUE,
    idChuyenNganh VARCHAR(50) NOT NULL,
    maGV VARCHAR(50) NOT NULL UNIQUE,
    hocHamHocVi VARCHAR(100),
    hanMucHuongDan INTEGER DEFAULT 5,
    CONSTRAINT FK_GIANGVIEN_NGUOIDUNG FOREIGN KEY (idNguoiDung) REFERENCES NGUOIDUNG(idNguoiDung),
    CONSTRAINT FK_GIANGVIEN_CHUYENNGANH FOREIGN KEY (idChuyenNganh) REFERENCES CHUYENNGANH(idChuyenNganh)
);

-- 7. BẢNG DOTDOAN
CREATE TABLE DOTDOAN (
    idDotDoAn VARCHAR(50) PRIMARY KEY,
    maDot VARCHAR(50) NOT NULL UNIQUE,
    tenDot VARCHAR(255) NOT NULL,
    nienKhoa VARCHAR(50) NOT NULL,
    hocKy VARCHAR(50) NOT NULL,
    maHocPhan VARCHAR(50),
    tenHocPhan VARCHAR(255),
    ngayBatDau DATE,
    ngayBatDauBaoVe DATE,
    ngayKetThucBaoVe DATE,
    trongSoGVHD NUMERIC(5,2),
    trongSoBaoCao NUMERIC(5,2),
    trongSoDoAn NUMERIC(5,2),
    trangThai VARCHAR(50)
);

-- 8. BẢNG DOTBAOCAO
CREATE TABLE DOTBAOCAO (
    idDotBaoCao VARCHAR(50) PRIMARY KEY,
    idDotDoAn VARCHAR(50) NOT NULL,
    tenDotBaoCao VARCHAR(255) NOT NULL,
    noiDungYeuCau TEXT,
    thuTu INTEGER NOT NULL,
    hanNop DATE NOT NULL,
    laBanCuoi BOOLEAN DEFAULT FALSE,
    CONSTRAINT FK_DOTBAOCAO_DOTDOAN FOREIGN KEY (idDotDoAn) REFERENCES DOTDOAN(idDotDoAn)
);

-- 9. BẢNG DANGKY
CREATE TABLE DANGKY (
    idDangKy VARCHAR(50) PRIMARY KEY,
    idSinhVien VARCHAR(50) NOT NULL,
    idDotDoAn VARCHAR(50) NOT NULL,
    trangThai VARCHAR(50),
    ngayDangKy DATE DEFAULT CURRENT_DATE,
    CONSTRAINT FK_DANGKY_SINHVIEN FOREIGN KEY (idSinhVien) REFERENCES SINHVIEN(idSinhVien),
    CONSTRAINT FK_DANGKY_DOTDOAN FOREIGN KEY (idDotDoAn) REFERENCES DOTDOAN(idDotDoAn)
);

-- 10. BẢNG NGANHANGDETAI
CREATE TABLE NGANHANGDETAI (
    idNganHangDeTai VARCHAR(50) PRIMARY KEY,
    idDotDoAn VARCHAR(50) NOT NULL,
    idChuyenNganh VARCHAR(50) NOT NULL,
    loaiDeTai VARCHAR(50),
    idGiangVienDeXuat VARCHAR(50) NULL,
    idSinhVienDeXuat VARCHAR(50) NULL,
    tenDeTai VARCHAR(500) NOT NULL,
    moTa TEXT,
    trangThai VARCHAR(50),
    CONSTRAINT FK_NGANHANGDETAI_DOTDOAN FOREIGN KEY (idDotDoAn) REFERENCES DOTDOAN(idDotDoAn),
    CONSTRAINT FK_NGANHANGDETAI_CHUYENNGANH FOREIGN KEY (idChuyenNganh) REFERENCES CHUYENNGANH(idChuyenNganh),
    CONSTRAINT FK_NGANHANGDETAI_GV FOREIGN KEY (idGiangVienDeXuat) REFERENCES GIANGVIEN(idGiangVien),
    CONSTRAINT FK_NGANHANGDETAI_SV FOREIGN KEY (idSinhVienDeXuat) REFERENCES SINHVIEN(idSinhVien)
);

-- 11. BẢNG HOIDONG
CREATE TABLE HOIDONG (
    idHoiDong VARCHAR(50) PRIMARY KEY,
    idDotDoAn VARCHAR(50) NOT NULL,
    idChuyenNganh VARCHAR(50) NOT NULL,
    maHoiDong VARCHAR(50) NOT NULL UNIQUE,
    tenHoiDong VARCHAR(255) NOT NULL,
    thoiGianBaoVe TIMESTAMP,
    diaDiem VARCHAR(255),
    trangThai VARCHAR(50),
    CONSTRAINT FK_HOIDONG_DOTDOAN FOREIGN KEY (idDotDoAn) REFERENCES DOTDOAN(idDotDoAn),
    CONSTRAINT FK_HOIDONG_CHUYENNGANH FOREIGN KEY (idChuyenNganh) REFERENCES CHUYENNGANH(idChuyenNganh)
);

-- 12. BẢNG DETAI
CREATE TABLE DETAI (
    idDeTai VARCHAR(50) PRIMARY KEY,
    idDangKy VARCHAR(50) NOT NULL UNIQUE,
    idNganHangDeTai VARCHAR(50) NULL UNIQUE,
    idGiangVienHuongDan VARCHAR(50) NOT NULL,
    idHoiDong VARCHAR(50) NULL,
    maDeTai VARCHAR(50) NOT NULL UNIQUE,
    tenDeTai VARCHAR(500) NOT NULL,
    moTa TEXT,
    linkGithub VARCHAR(500) NULL,
    linkDemo VARCHAR(500) NULL,
    trangThai VARCHAR(50),
    gvhdDaDuyet BOOLEAN DEFAULT FALSE,
    nhanXetTongKet TEXT NULL,
    diemGVHD NUMERIC(4,2) NULL,
    diemBaoCaoTB NUMERIC(4,2) NULL,
    diemDoAnTB NUMERIC(4,2) NULL,
    diemTongKet NUMERIC(4,2) NULL,
    xepLoai VARCHAR(50) NULL,
    daKhoaDiem BOOLEAN DEFAULT FALSE,
    CONSTRAINT FK_DETAI_DANGKY FOREIGN KEY (idDangKy) REFERENCES DANGKY(idDangKy),
    CONSTRAINT FK_DETAI_NGANHANGDETAI FOREIGN KEY (idNganHangDeTai) REFERENCES NGANHANGDETAI(idNganHangDeTai),
    CONSTRAINT FK_DETAI_GVHD FOREIGN KEY (idGiangVienHuongDan) REFERENCES GIANGVIEN(idGiangVien),
    CONSTRAINT FK_DETAI_HOIDONG FOREIGN KEY (idHoiDong) REFERENCES HOIDONG(idHoiDong)
);

-- 13. BẢNG BAOCAO
CREATE TABLE BAOCAO (
    idBaoCao VARCHAR(50) PRIMARY KEY,
    idDeTai VARCHAR(50) NOT NULL,
    idDotBaoCao VARCHAR(50) NOT NULL,
    phienBan INTEGER DEFAULT 1,
    tenTep VARCHAR(255) NOT NULL,
    urlTep VARCHAR(500) NOT NULL,
    ngayNop TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    nopTre BOOLEAN DEFAULT FALSE,
    phanHoiGVHD TEXT NULL,
    trangThai VARCHAR(50),
    CONSTRAINT FK_BAOCAO_DETAI FOREIGN KEY (idDeTai) REFERENCES DETAI(idDeTai),
    CONSTRAINT FK_BAOCAO_DOTBAOCAO FOREIGN KEY (idDotBaoCao) REFERENCES DOTBAOCAO(idDotBaoCao)
);

-- 14. BẢNG HINHANHDETAI
CREATE TABLE HINHANHDETAI (
    idHinhAnh VARCHAR(50) PRIMARY KEY,
    idDeTai VARCHAR(50) NOT NULL,
    tenHinh VARCHAR(255) NOT NULL,
    url VARCHAR(500) NOT NULL,
    moTa TEXT NULL,
    CONSTRAINT FK_HINHANHDETAI_DETAI FOREIGN KEY (idDeTai) REFERENCES DETAI(idDeTai)
);

-- 15. BẢNG HOIDONGGIANGVIEN
CREATE TABLE HOIDONGGIANGVIEN (
    idHoiDongGiangVien VARCHAR(50) PRIMARY KEY,
    idHoiDong VARCHAR(50) NOT NULL,
    idGiangVien VARCHAR(50) NOT NULL,
    vaiTro VARCHAR(50),
    CONSTRAINT FK_HDGV_HOIDONG FOREIGN KEY (idHoiDong) REFERENCES HOIDONG(idHoiDong),
    CONSTRAINT FK_HDGV_GIANGVIEN FOREIGN KEY (idGiangVien) REFERENCES GIANGVIEN(idGiangVien)
);

-- 16. BẢNG PHIEUCHAMDIEM
CREATE TABLE PHIEUCHAMDIEM (
    idPhieuChamDiem VARCHAR(50) PRIMARY KEY,
    idDeTai VARCHAR(50) NOT NULL,
    idHoiDongGiangVien VARCHAR(50) NOT NULL,
    diemBaoCao NUMERIC(4,2) NULL,
    diemDoAn NUMERIC(4,2) NULL,
    nhanXet TEXT NULL,
    trangThai VARCHAR(50),
    ngayCham TIMESTAMP NULL,
    CONSTRAINT FK_PHIEUCHAMDIEM_DETAI FOREIGN KEY (idDeTai) REFERENCES DETAI(idDeTai),
    CONSTRAINT FK_PHIEUCHAMDIEM_HDGV FOREIGN KEY (idHoiDongGiangVien) REFERENCES HOIDONGGIANGVIEN(idHoiDongGiangVien)
);

-- 17. BẢNG TINNHAN
CREATE TABLE TINNHAN (
    idTinNhan VARCHAR(50) PRIMARY KEY,
    idDeTai VARCHAR(50) NOT NULL,
    idNguoiGui VARCHAR(50) NOT NULL,
    noiDung TEXT NOT NULL,
    daDoc BOOLEAN DEFAULT FALSE,
    ngayGui TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TINNHAN_DETAI FOREIGN KEY (idDeTai) REFERENCES DETAI(idDeTai),
    CONSTRAINT FK_TINNHAN_NGUOIDUNG FOREIGN KEY (idNguoiGui) REFERENCES NGUOIDUNG(idNguoiDung)
);

-- 18. BẢNG THONGBAO
CREATE TABLE THONGBAO (
    idThongBao VARCHAR(50) PRIMARY KEY,
    idNguoiGui VARCHAR(50) NOT NULL,
    idDotDoAn VARCHAR(50) NULL,
    tieuDe VARCHAR(255) NOT NULL,
    noiDung TEXT NOT NULL,
    ngayTao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_THONGBAO_NGUOIDUNG FOREIGN KEY (idNguoiGui) REFERENCES NGUOIDUNG(idNguoiDung),
    CONSTRAINT FK_THONGBAO_DOTDOAN FOREIGN KEY (idDotDoAn) REFERENCES DOTDOAN(idDotDoAn)
);

-- 19. BẢNG TEPTHONGBAO
CREATE TABLE TEPTHONGBAO (
    idTepThongBao VARCHAR(50) PRIMARY KEY,
    idThongBao VARCHAR(50) NOT NULL,
    tenTep VARCHAR(255) NOT NULL,
    urlTep VARCHAR(500) NOT NULL,
    CONSTRAINT FK_TEPTHONGBAO_THONGBAO FOREIGN KEY (idThongBao) REFERENCES THONGBAO(idThongBao)
);

-- 20. BẢNG NGUOINHANTHONGBAO
CREATE TABLE NGUOINHANTHONGBAO (
    idNguoiNhanThongBao VARCHAR(50) PRIMARY KEY,
    idThongBao VARCHAR(50) NOT NULL,
    idNguoiNhan VARCHAR(50) NOT NULL,
    daDoc BOOLEAN DEFAULT FALSE,
    ngayDoc TIMESTAMP NULL,
    CONSTRAINT FK_NNTB_THONGBAO FOREIGN KEY (idThongBao) REFERENCES THONGBAO(idThongBao),
    CONSTRAINT FK_NNTB_NGUOIDUNG FOREIGN KEY (idNguoiNhan) REFERENCES NGUOIDUNG(idNguoiDung)
);

